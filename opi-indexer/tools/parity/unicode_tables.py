"""Prints opi-sns's src/unicode_tables.rs: the Unicode 17.0.0 tables the SNS
rules read, so results do not depend on the Rust toolchain.

Run it with the parity venv's Python 3.15, whose `unicodedata` is Unicode
17.0.0:

  python3 -I opi-indexer/tools/parity/unicode_tables.py \
    > opi-indexer/crates/opi-sns/src/unicode_tables.rs

Tables:
- WHITE_SPACE: the White_Space property of Unicode 17.0.0 PropList.txt
  (Python does not expose it, so it is listed here).
- LOWER: code points whose full lowercase mapping (`chr(cp).lower()`) differs
  from the code point. U+03A3 maps to its non-final form; the final form is
  contextual.
- CASED and CASE_IGNORABLE: the properties the final sigma context reads
  (Unicode 17 section 3.13, as CPython's handle_capital_sigma applies it).
  `unicodedata` does not expose them, so they are probed through
  `str.lower()`:
    T1 = lower(c + 'Σ') ends in 'ς'        <=> cased(c) and not ignorable(c)
    T2 = lower('A' + c + 'Σ') ends in 'ς'  <=> ignorable(c) or cased(c)
    T3 = lower('AΣ' + c)[1] == 'ς'         <=> ignorable(c) or not cased(c)
  so ignorable(c) = T2 and T3, and CASED holds T1 (the cased code points that
  are not ignorable, the only ones the context test reaches).
- ZS, LL, LM, LO, LT, LU, NL, MN, MC, ND, PC: the general categories the
  JSON5 grammar tests (whitespace and identifiers).
"""

import sys
import unicodedata

if unicodedata.unidata_version != '17.0.0':
  sys.exit(f'Unicode {unicodedata.unidata_version}; the tables are for Unicode 17.0.0')

MAX = 0x110000
SIGMA = 'Σ'

# White_Space in Unicode 17.0.0 PropList.txt.
WHITE_SPACE = ([0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x20, 0x85, 0xA0, 0x1680]
               + list(range(0x2000, 0x200B))
               + [0x2028, 0x2029, 0x202F, 0x205F, 0x3000])


def ranges(pred):
  out = []
  start = None
  for cp in range(MAX):
    if pred(cp):
      if start is None:
        start = cp
    elif start is not None:
      out.append((start, cp - 1))
      start = None
  if start is not None:
    out.append((start, MAX - 1))
  return out


def final_sigma(s, i):
  return s.lower()[i] == 'ς'


def t1(c):
  return final_sigma(c + SIGMA, -1)


def t2(c):
  return final_sigma('A' + c + SIGMA, -1)


def t3(c):
  return final_sigma('A' + SIGMA + c, 1)


def emit_ranges(name, doc, rs):
  print(f'/// {doc}')
  print(f'pub(crate) const {name}: &[(u32, u32)] = &[')
  for i in range(0, len(rs), 6):
    print('    ' + ' '.join(f'(0x{a:X}, 0x{b:X}),' for a, b in rs[i:i + 6]))
  print('];')
  print()


def main():
  lower = []
  for cp in range(MAX):
    low = chr(cp).lower()
    if low != chr(cp):
      lower.append((cp, [ord(ch) for ch in low]))
  ignorable = lambda cp: t2(chr(cp)) and t3(chr(cp))
  cased = lambda cp: t1(chr(cp))
  cat = lambda cats: (lambda cp: unicodedata.category(chr(cp)) in cats)

  print('// Generated by opi-indexer/tools/parity/unicode_tables.py; do not edit.')
  print(f'// Unicode {unicodedata.unidata_version}.')
  print()
  print('/// White_Space, sorted.')
  print('pub(crate) const WHITE_SPACE: &[u32] = &[')
  for i in range(0, len(WHITE_SPACE), 8):
    print('    ' + ' '.join(f'0x{cp:X},' for cp in WHITE_SPACE[i:i + 8]))
  print('];')
  print()
  print('/// Full lowercase mappings that change the code point, sorted by code point.')
  print('pub(crate) const LOWER: &[(u32, &[u32])] = &[')
  for i in range(0, len(lower), 4):
    print('    ' + ' '.join(
        f'(0x{cp:X}, &[{", ".join(f"0x{x:X}" for x in low)}]),'
        for cp, low in lower[i:i + 4]))
  print('];')
  print()
  emit_ranges('CASED', 'Cased and not case-ignorable.', ranges(cased))
  emit_ranges('CASE_IGNORABLE', 'Case-ignorable.', ranges(ignorable))
  for category in ('Zs', 'Ll', 'Lm', 'Lo', 'Lt', 'Lu', 'Nl', 'Mn', 'Mc', 'Nd', 'Pc'):
    emit_ranges(category.upper(), f'General category {category}.',
                ranges(cat({category})))


main()
