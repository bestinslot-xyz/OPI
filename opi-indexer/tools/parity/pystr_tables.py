"""Prints opi-sns's src/pytables.rs: the Python string and Unicode tables the
SNS rules read.

Run it with the parity venv's Python, the same interpreter that generates
sns_vectors.py's fixtures:

  python3 -I opi-indexer/tools/parity/pystr_tables.py \
    > opi-indexer/crates/opi-sns/src/pytables.rs

Every table comes from the running interpreter:
- PY_SPACE: code points with `chr(cp).isspace()`, the whitespace that
  `str.split()` and `str.strip()` use.
- LOWER: code points whose `chr(cp).lower()` differs from `chr(cp)`, with the
  lowercase. U+03A3 maps to its non-final form; the final form is contextual.
- CASED and CASE_IGNORABLE: the properties `str.lower()` reads for the final
  sigma context (Objects/unicodeobject.c handle_capital_sigma). Python does
  not expose them, so they are probed through `str.lower()` itself:
    T1 = lower(c + 'Σ') ends in 'ς'        <=> cased(c) and not ignorable(c)
    T2 = lower('A' + c + 'Σ') ends in 'ς'  <=> ignorable(c) or cased(c)
    T3 = lower('AΣ' + c)[1] == 'ς'         <=> ignorable(c) or not cased(c)
  so ignorable(c) = T2 and T3, and CASED holds T1 (the cased code points that
  are not ignorable, the only ones the context test reaches).
- ZS, LL, LM, LO, LT, LU, NL, MN, MC, ND, PC: the `unicodedata.category`
  values the json5 0.12.0 grammar tests (json5/parser.py `_ws__c8_`,
  `_other_id_start_`, `_id_continue_`).
"""

import sys
import unicodedata

MAX = 0x110000
SIGMA = 'Σ'


def ranges(pred):
  out = []
  start = None
  for cp in range(MAX):
    if pred(cp):
      if start is None:
        start = cp
    elif start is not None:
      out.append((start, cp - 1))
      start = None
  if start is not None:
    out.append((start, MAX - 1))
  return out


def final_sigma(s, i):
  return s.lower()[i] == 'ς'


def t1(c):
  return final_sigma(c + SIGMA, -1)


def t2(c):
  return final_sigma('A' + c + SIGMA, -1)


def t3(c):
  return final_sigma('A' + SIGMA + c, 1)


def emit_ranges(name, doc, rs):
  print(f'/// {doc}')
  print(f'pub(crate) const {name}: &[(u32, u32)] = &[')
  for i in range(0, len(rs), 6):
    print('    ' + ' '.join(f'(0x{a:X}, 0x{b:X}),' for a, b in rs[i:i + 6]))
  print('];')
  print()


def main():
  space = [cp for cp in range(MAX) if chr(cp).isspace()]
  lower = []
  for cp in range(MAX):
    low = chr(cp).lower()
    if low != chr(cp):
      lower.append((cp, [ord(ch) for ch in low]))
  ignorable = lambda cp: t2(chr(cp)) and t3(chr(cp))
  cased = lambda cp: t1(chr(cp))
  cat = lambda cats: (lambda cp: unicodedata.category(chr(cp)) in cats)

  print('// Generated by opi-indexer/tools/parity/pystr_tables.py; do not edit.')
  print(f'// Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.')
  print()
  print('/// Code points with `str.isspace()`.')
  print('pub(crate) const PY_SPACE: &[u32] = &[')
  for i in range(0, len(space), 8):
    print('    ' + ' '.join(f'0x{cp:X},' for cp in space[i:i + 8]))
  print('];')
  print()
  print('/// `str.lower()` of single code points that change, sorted by code point.')
  print('pub(crate) const LOWER: &[(u32, &[u32])] = &[')
  for i in range(0, len(lower), 4):
    print('    ' + ' '.join(
        f'(0x{cp:X}, &[{", ".join(f"0x{x:X}" for x in low)}]),'
        for cp, low in lower[i:i + 4]))
  print('];')
  print()
  emit_ranges('CASED', 'Cased and not case-ignorable, as `str.lower()` sees them.',
              ranges(cased))
  emit_ranges('CASE_IGNORABLE', 'Case-ignorable, as `str.lower()` sees them.',
              ranges(ignorable))
  for category in ('Zs', 'Ll', 'Lm', 'Lo', 'Lt', 'Lu', 'Nl', 'Mn', 'Mc', 'Nd', 'Pc'):
    emit_ranges(category.upper(), f'General category {category}.',
                ranges(cat({category})))


main()
